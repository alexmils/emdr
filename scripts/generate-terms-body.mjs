/**
 * Prepare Termly HTML → bundled module for Next standalone (no runtime fs).
 * Usage: npx tsx scripts/generate-terms-body.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { prepareTermsHtml } from "../lib/legal/terms-html.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "content/legal/terms-of-service.termly.html");
const out = path.join(root, "lib/legal/terms-body.generated.ts");

const raw = fs.readFileSync(src, "utf8");
const prepared = prepareTermsHtml(raw);
const file = `/* Auto-generated by scripts/generate-terms-body.mjs — do not edit by hand. */
export const TERMS_BODY_HTML = ${JSON.stringify(prepared)};
`;
fs.writeFileSync(out, file);
console.log("wrote", out, "chars", prepared.length);
