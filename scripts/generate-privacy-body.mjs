/**
 * Prepare Termly Privacy HTML → bundled module for Next standalone.
 * Usage: node scripts/generate-privacy-body.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { preparePrivacyHtml } from "../lib/legal/privacy-html.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "content/legal/privacy-policy.termly.html");
const out = path.join(root, "lib/legal/privacy-body.generated.ts");

const raw = fs.readFileSync(src, "utf8");
const prepared = preparePrivacyHtml(raw);
const file = `/* Auto-generated by scripts/generate-privacy-body.mjs — do not edit by hand. */
export const PRIVACY_BODY_HTML = ${JSON.stringify(prepared)};
`;
fs.writeFileSync(out, file);
console.log("wrote", out, "chars", prepared.length);
